import React, { useState } from 'react';
import { Calculator, Info } from 'lucide-react';

export default function CorporateTaxCalculator({ lang }: any) {
  const [netProfit, setNetProfit] = useState<number | ''>('');
  const [isSme, setIsSme] = useState<boolean>(true);

  let tax = 0;
  if (netProfit !== '') {
    if (isSme) {
      if (netProfit <= 300000) {
        tax = 0;
      } else if (netProfit <= 3000000) {
        tax = (netProfit - 300000) * 0.15;
      } else {
        tax = (3000000 - 300000) * 0.15 + (netProfit - 3000000) * 0.20;
      }
    } else {
      tax = netProfit * 0.20;
    }
  }

  return (
    <div className="space-y-6">
      <div className="bg-white p-6 rounded-lg shadow-md">
        <h2 className="text-2xl font-bold mb-4 flex items-center">
          <Calculator className="mr-2" />
          เครื่องมือคำนวณภาษีเงินได้นิติบุคคล
        </h2>
        <div className="space-y-4">
          <div>
            <label className="block text-sm font-medium text-gray-700 mb-1">
              กำไรสุทธิทางภาษี (Net Profit for Tax)
            </label>
            <input
              type="number"
              value={netProfit}
              onChange={(e) => setNetProfit(Number(e.target.value))}
              className="w-full p-2 border rounded-md focus:ring-2 focus:ring-blue-500"
              placeholder="กรอกกำไรสุทธิ..."
            />
          </div>
          <div>
            <label className="flex items-center space-x-2 cursor-pointer">
              <input
                type="checkbox"
                checked={isSme}
                onChange={(e) => setIsSme(e.target.checked)}
                className="rounded text-blue-600 focus:ring-blue-500 w-5 h-5"
              />
              <span className="text-sm font-medium text-gray-700">เป็นธุรกิจ SME (ทุนจดทะเบียนไม่เกิน 5 ล้านบาท และรายได้ไม่เกิน 30 ล้านบาท)</span>
            </label>
          </div>
          
          <div className="bg-blue-50 p-4 rounded-md mt-6">
            <h3 className="text-lg font-semibold text-blue-800 mb-2">ภาษีที่ต้องชำระโดยประมาณ</h3>
            <div className="text-3xl font-bold text-blue-900">
              ฿{tax.toLocaleString('th-TH', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}
            </div>
            <p className="text-sm text-blue-700 mt-2">
              * คำนวณจากอัตราภาษี {isSme ? 'SME แบบขั้นบันได' : 'นิติบุคคลทั่วไป (20%)'}
            </p>
          </div>
        </div>
      </div>

      <div className="bg-white p-6 rounded-lg shadow-md prose max-w-none">
        <h2>ภาษีเงินได้นิติบุคคล (Corporate Income Tax) คืออะไร?</h2>
        <p>ภาษีเงินได้นิติบุคคล คือ ภาษีที่จัดเก็บจากเงินได้ของบริษัทหรือห้างหุ้นส่วนนิติบุคคล ที่จดทะเบียนตามประมวลกฎหมายแพ่งและพาณิชย์ หรือนิติบุคคลที่ตั้งขึ้นตามกฎหมายต่างประเทศแต่เข้ามาประกอบกิจการในประเทศไทย โดยฐานภาษีที่สำคัญที่สุดและใช้กันอย่างแพร่หลายคือ <strong>กำไรสุทธิ (Net Profit)</strong> ซึ่งคำนวณจากรายได้หักด้วยรายจ่ายตามเงื่อนไขที่ประมวลรัษฎากรกำหนด</p>
        
        <h3>อัตราภาษีเงินได้นิติบุคคลในปัจจุบัน</h3>
        <p>การจัดเก็บภาษีเงินได้นิติบุคคลของประเทศไทยในปัจจุบัน มีการแบ่งอัตราภาษีตามขนาดของธุรกิจ เพื่อเป็นการสนับสนุนและช่วยเหลือธุรกิจขนาดกลางและขนาดย่อม (SME) โดยแบ่งออกเป็น 2 กรณีหลักๆ ดังนี้:</p>
        
        <h4>1. สำหรับนิติบุคคลทั่วไป (Non-SME)</h4>
        <p>นิติบุคคลที่ไม่ได้เข้าเงื่อนไข SME (คือมีทุนจดทะเบียนชำระแล้วเกิน 5 ล้านบาท หรือมีรายได้จากการขายสินค้าและบริการในรอบระยะเวลาบัญชีเกิน 30 ล้านบาท) จะต้องเสียภาษีในอัตราคงที่คือ <strong>20% ของกำไรสุทธิ</strong> ตั้งแต่บาทแรก</p>

        <h4>2. สำหรับธุรกิจ SME</h4>
        <p>นิติบุคคลที่เข้าเงื่อนไข SME (ทุนจดทะเบียนชำระแล้วไม่เกิน 5 ล้านบาท <strong>และ</strong> รายได้จากการขายสินค้าและบริการไม่เกิน 30 ล้านบาทตลอดรอบระยะเวลาบัญชี) จะได้รับการยกเว้นและลดหย่อนอัตราภาษีแบบขั้นบันได ดังนี้:</p>
        <ul>
          <li>กำไรสุทธิ 1 - 300,000 บาท: <strong>ยกเว้นภาษี (0%)</strong></li>
          <li>กำไรสุทธิ 300,001 - 3,000,000 บาท: <strong>เสียภาษีในอัตรา 15%</strong></li>
          <li>กำไรสุทธิ 3,000,001 บาท ขึ้นไป: <strong>เสียภาษีในอัตรา 20%</strong></li>
        </ul>

        <h3>ความสำคัญของการวางแผนภาษี (Tax Planning)</h3>
        <p>การเข้าใจวิธีการคำนวณและอัตราภาษีเงินได้นิติบุคคล เป็นหัวใจสำคัญของการวางแผนภาษี ซึ่งจะช่วยให้ผู้ประกอบการสามารถ:</p>
        <ul>
          <li><strong>บริหารสภาพคล่อง:</strong> การคาดการณ์ภาระภาษีล่วงหน้าช่วยให้บริษัทสามารถกันเงินสำรองไว้จ่ายภาษีได้อย่างถูกต้อง ไม่กระทบกับกระแสเงินสด (Cash Flow) ของกิจการ</li>
          <li><strong>เพิ่มความสามารถในการทำกำไร:</strong> การใช้สิทธิประโยชน์ทางภาษีที่รัฐบาลสนับสนุน (เช่น การหักค่าใช้จ่ายได้ 1.5 - 2 เท่า สำหรับการวิจัย พัฒนา หรือการจ้างงานผู้สูงอายุ) จะช่วยลดฐานกำไรสุทธิทางภาษี ทำให้เสียภาษีน้อยลงอย่างถูกต้องตามกฎหมาย</li>
          <li><strong>ลดความเสี่ยงจากการถูกตรวจสอบ:</strong> การคำนวณภาษีผิดพลาดหรือหลีกเลี่ยงภาษี อาจนำไปสู่การถูกปรับและเสียเงินเพิ่ม ซึ่งเป็นต้นทุนที่ไม่จำเป็นและส่งผลเสียต่อภาพลักษณ์ขององค์กร</li>
        </ul>

        <h3>ข้อควรระวังในการคำนวณกำไรสุทธิทางภาษี</h3>
        <p>ผู้ประกอบการหลายท่านมักสับสนระหว่าง "กำไรสุทธิทางบัญชี" และ "กำไรสุทธิทางภาษี" ในการคำนวณภาษีเงินได้นิติบุคคล จะต้องใช้ <strong>กำไรสุทธิทางภาษี</strong> ซึ่งเกิดจากการนำกำไรสุทธิทางบัญชีมาปรับปรุงรายการ (Tax Adjustment) ตามมาตรา 65 ทวิ และ 65 ตรี แห่งประมวลรัษฎากร ตัวอย่างเช่น การบวกกลับรายจ่ายต้องห้าม (เช่น ค่ารับรองที่เกินเกณฑ์, รายจ่ายส่วนตัวของผู้บริหาร, ภาษีมูลค่าเพิ่มที่ขอคืนไม่ได้) หรือการหักรายได้ที่ได้รับยกเว้น เป็นต้น</p>

        <p>ดังนั้น นอกจากการใช้เครื่องมือคำนวณภาษีเบื้องต้นเพื่อประเมินภาระภาษีแล้ว ธุรกิจควรมีนักบัญชีหรือผู้สอบบัญชีที่เชี่ยวชาญในการจัดทำและตรวจสอบงบการเงิน เพื่อให้การเสียภาษีเป็นไปอย่างถูกต้อง ครบถ้วน และเกิดประโยชน์สูงสุดแก่กิจการ</p>
      </div>
    </div>
  );
}
